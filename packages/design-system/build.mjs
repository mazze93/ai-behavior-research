// Bundle src/index.ts as ONE classic IIFE script that reads window.React /
// window.ReactDOM and assigns window.CharcoalPorcelain, plus its stylesheet and
// concatenated type declarations. Output: dist/ (git-ignored).
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, copyFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const NS = 'CharcoalPorcelain';
const COMPONENTS = ['SpectralFold', 'StudyRoom', 'Masthead', 'Button', 'TextLink', 'StudyRow', 'ReleaseCard', 'Field', 'Notice',
  'IntervalPlot', 'StripPlot', 'TrendChart', 'MatrixHeatmap', 'ProportionBars', 'StatFigure', 'EvidenceLedger'];

const globals = {
  name: 'react-globals',
  setup(b) {
    b.onResolve({ filter: /^react(-dom)?(\/.*)?$/ }, a => ({ path: a.path, namespace: 'g' }));
    b.onLoad({ filter: /.*/, namespace: 'g' }, a => {
      if (a.path === 'react') return { contents: 'module.exports = window.React;', loader: 'js' };
      if (a.path.startsWith('react-dom')) return { contents: 'module.exports = window.ReactDOM;', loader: 'js' };
      if (a.path === 'react/jsx-runtime') return { loader: 'js', contents: `
        const R = window.React;
        const jsx = (type, props, key) => R.createElement(type, key === undefined ? props : { ...props, key });
        module.exports = { jsx, jsxs: jsx, Fragment: R.Fragment };` };
      throw new Error(`unshimmed import ${a.path}`);
    });
  },
};

rmSync('dist', { recursive: true, force: true });
mkdirSync('dist', { recursive: true });
const out = await build({
  entryPoints: ['src/index.ts'], bundle: true, format: 'iife', globalName: NS, minify: process.env.DEBUG !== "1", write: false,
  jsx: 'automatic', target: 'es2020', define: { 'process.env.NODE_ENV': '"production"' }, plugins: [globals], legalComments: 'none',
  tsconfigRaw: { compilerOptions: { jsx: 'react-jsx', jsxImportSource: 'react' } },
});
let js = out.outputFiles[0].text;
if (/<\/script|<!--/i.test(js)) js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '\\x3C!--');
const header = `/* @ds-bundle: ${JSON.stringify({ format: 4, namespace: NS, components: COMPONENTS.map(name => ({ name })) })} */\n`;
writeFileSync('dist/bundle.js', header + js + `\nwindow.${NS}=${NS};\n`);
copyFileSync('src/styles.css', 'dist/bundle.css');

// Types as documentation: per-file declarations concatenated, local imports dropped.
execFileSync('npx', ['tsc', '-p', 'tsconfig.json', '--declaration', '--emitDeclarationOnly', '--noEmit', 'false', '--outDir', 'dist/types'], { stdio: 'inherit' });
const files = [];
const walk = d => readdirSync(d).forEach(f => { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : p.endsWith('.d.ts') && files.push(p); });
walk('dist/types');
const dts = files.sort().filter(f => !f.endsWith('src/index.d.ts')).map(f => `// ${relative('dist/types', f)}\n` + readFileSync(f, 'utf8')
  .replace(/\bProps\b/g, /(SpectralFold|StudyRoom)\.d\.ts$/.test(f) ? f.match(/(\w+)\.d\.ts$/)[1] + 'Props' : 'Props')
  .replace(/^import .*;\n/gm, '').replace(/^export \{[^}]*\} from .*;\n/gm, '').replace(/^export default function (\w+)/m, 'export declare function $1')).join('\n');
writeFileSync('dist/index.d.ts', `// ${NS} — types as documentation (generated by build.mjs)\n` + dts);
rmSync('dist/types', { recursive: true, force: true });
console.log(`bundle.js ${(statSync('dist/bundle.js').size / 1024).toFixed(1)} KB`);

// Previews: inline fixture JSON at /*@data:<file>*/null markers → dist/previews/<Comp>/preview.html.
for (const f of readdirSync('previews').filter(f => f.endsWith('.html'))) {
  const html = readFileSync(join('previews', f), 'utf8').replace(/\/\*@data:([\w.-]+)\*\/null/g, (_, name) =>
    readFileSync(join('previews/data', name), 'utf8').trim().replace(/</g, '\\u003c'));
  mkdirSync(join('dist/previews', f.replace(/\.html$/, '')), { recursive: true });
  writeFileSync(join('dist/previews', f.replace(/\.html$/, ''), 'preview.html'), html);
}
console.log('previews inlined');
